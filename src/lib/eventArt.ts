export function eventArtId(value: string): EventArtId {
  const id = value.replace(/^icon:/, '')
  return eventArtOptions.find((option) => option.id === id)?.id || legacy[value] || 'heart'
}
export function eventArtConfig(value: string) {
  return eventArtOptions.find((option) => option.id === eventArtId(value))!
}

export function filterEventArt(group: EventArtGroup, query: string) {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  return eventArtOptions.filter((option) => {
    const text =
      `${option.label} ${option.category} ${option.keywords} ${option.id}`.toLocaleLowerCase()
    return (group === 'all' || option.group === group) && words.every((word) => text.includes(word))
  })
}
